# Writes app/src/main/res:
#   drawable/ic_launcher_background.xml, ic_launcher_foreground.xml, ic_launcher_monochrome.xml: the adaptive
#     icon's layers as vector drawables (icon-light.svg's shapes, its 1024 units drawn 64 dp wide in the 108 dp
#     canvas, so the screen and knobs sit inside the 66 dp safe zone; the keys and the keybed run on to the edges).
#     Vector drawables have no blur and no dashes: the LEDs' glow is two soft rects, the knobs' dashed ring a faint
#     solid one. The monochrome layer (Android 13 themed icons; only its alpha counts) is the mark of icon-tinted.svg:
#     the screen's frame, the wave, the knobs' rings and pointers, the keys half strong, their lit LEDs.
#   mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml: the adaptive icon.
#   mipmap-<density>/ic_launcher.png, ic_launcher_round.png: legacy icons from the 1024 PNG (rounded square and
#     circle; never used with minSdk 29, kept for completeness).
#
#   CR_PYTHON (python.org 3.11 with Pillow) scripts/make_icon.py [path to AppIcon-light-1024.png]
# Without the PNG argument it reads it from ../RemoteFM1IOS (git show edf2039:...).
import io
import os
import subprocess
import sys

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
IOS = os.path.join(os.path.dirname(ROOT), "RemoteFM1IOS")
IOS_COMMIT = "edf2039"

# 1024 icon units -> 108 dp canvas: 64 dp wide, centred
SCALE = 64 / 1024
SHIFT = 54 - 512 * SCALE          # 22 dp
LO, HI = -352, 1376               # the canvas's edges in icon units

HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: GPL-3.0-only -->
<!-- Generated by scripts/make_icon.py from RemoteFM1IOS %s design/icon/%s. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="%g" android:translateY="%g" android:scaleX="%g" android:scaleY="%g">
"""
TAIL = """    </group>
</vector>
"""


def rrect(x, y, w, h, r=0):
    r = min(r, w / 2, h / 2)
    if r <= 0:
        return "M%g,%g h%g v%g h%g Z" % (x, y, w, h, -w)
    return ("M%g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g Z"
            % (x + r, y, w - 2 * r, r, r, r, r, h - 2 * r, r, r, -r, r, -(w - 2 * r), r, r, -r, -r, -(h - 2 * r),
               r, r, r, -r))


def circle(cx, cy, r):
    return "M%g,%g a%g,%g 0 1 0 %g,0 a%g,%g 0 1 0 %g,0 Z" % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)


def fill(d, color, alpha=1.0, even_odd=False):
    a = '' if alpha >= 1 else ' android:fillAlpha="%g"' % alpha
    t = ' android:fillType="evenOdd"' if even_odd else ''
    return '        <path android:pathData="%s" android:fillColor="%s"%s%s />\n' % (d, color, a, t)


def stroke(d, color, width, alpha=1.0, cap="round"):
    a = '' if alpha >= 1 else ' android:strokeAlpha="%g"' % alpha
    return ('        <path android:pathData="%s" android:strokeColor="%s" android:strokeWidth="%g"%s'
            ' android:strokeLineCap="%s" android:strokeLineJoin="round" />\n' % (d, color, width, a, cap))


def rotated(deg, px, py, body):
    return ('        <group android:rotation="%g" android:pivotX="%g" android:pivotY="%g">\n%s        </group>\n'
            % (deg, px, py, body.replace("        <", "            <")))


WAVE = ("M196 368 L200 324 L204 289 L208 269 L212 264 L216 274 L220 294 L224 317 L228 340 L232 361 L236 376 L240 387 "
        "L244 394 L248 396 L252 395 L256 391 L260 385 L264 377 L268 368 L272 359 L276 351 L280 345 L284 341 L288 340 "
        "L292 342 L296 349 L300 360 L304 375 L308 396 L312 419 L316 442 L320 462 L324 472 L328 467 L332 447 L336 412 "
        "L340 368 L344 324 L348 289 L352 269 L356 264 L360 274 L364 294 L368 317 L372 340 L376 361 L380 376 L384 387 "
        "L388 394 L392 396 L396 395 L400 391 L404 385 L408 377 L412 368 L416 359 L420 351 L424 345 L428 341 L432 340 "
        "L436 342 L440 349 L444 360 L448 375 L452 396 L456 419 L460 442 L464 462 L468 472 L472 467 L476 447 L480 412 "
        "L484 368")
KEYS = [94, 270, 446, 622, 798]
LIT = {270, 622}
KNOBS = [(788, 250, -40), (788, 480, 60)]
KEY_H = HI - 740                  # the keys run on past the canvas's bottom edge


def head(src):
    return HEAD % (IOS_COMMIT, src, SHIFT, SHIFT, SCALE, SCALE)


def background():
    s = head("icon-light.svg")
    s += fill(rrect(LO, LO, HI - LO, HI - LO), "#EE7A3C")
    s += fill(rrect(LO, 700, HI - LO, HI - 700), "#874332")
    return s + TAIL


def foreground():
    s = head("icon-light.svg")
    s += fill(rrect(LO, 700, HI - LO, 10), "#000000", 0.18)
    for x in KEYS:
        s += fill(rrect(x, 768, 132, KEY_H, 60), "#64301F")
        s += fill(rrect(x, 752, 132, KEY_H, 60), "#A9614B")
        s += fill(rrect(x, 759, 132, KEY_H, 60), "#924E3A")
        lx = x + 57
        if x in LIT:
            s += fill(rrect(lx - 14, 798, 46, 158, 23), "#FFE6A8", 0.18)       # (the glow)
            s += fill(rrect(lx - 7, 805, 32, 144, 16), "#FFE6A8", 0.35)
            s += fill(rrect(lx, 812, 18, 130, 9), "#FFE6A8")
        else:
            s += fill(rrect(lx, 812, 18, 130, 9), "#6F6668")
    s += fill(rrect(120, 152, 440, 440, 52), "#000000", 0.25)
    s += fill(rrect(120, 140, 440, 440, 52), "#141210")
    s += fill(rrect(146, 166, 388, 388, 20), "#C9D6EA")
    s += stroke(WAVE, "#13203A", 34)
    for cx, cy, deg in KNOBS:
        s += fill(circle(cx, cy + 12, 96), "#000000", 0.28)
        s += fill(circle(cx, cy, 96), "#1B1715")
        s += stroke(circle(cx, cy, 86), "#FFFFFF", 16, 0.08, "butt")          # (iOS: a dashed ring at 0.16)
        s += fill(circle(cx, cy, 68), "#FFFFFF", 0.07)
        s += rotated(deg, cx, cy, stroke("M%g,%g L%g,%g" % (cx, cy - 84, cx, cy - 44), "#F4EDE6", 18))
    return s + TAIL


def monochrome():
    s = head("icon-tinted.svg")
    for x in KEYS:
        s += fill(rrect(x, 752, 132, KEY_H, 60), "#FFFFFF", 0.45)
        if x in LIT:
            s += fill(rrect(x + 57, 812, 18, 130, 9), "#FFFFFF")
    s += fill(rrect(120, 140, 440, 440, 52) + " " + rrect(150, 170, 380, 380, 20), "#FFFFFF", even_odd=True)
    s += stroke(WAVE, "#FFFFFF", 34)
    for cx, cy, deg in KNOBS:
        s += stroke(circle(cx, cy, 88), "#FFFFFF", 16)
        s += rotated(deg, cx, cy, stroke("M%g,%g L%g,%g" % (cx, cy - 84, cx, cy - 44), "#FFFFFF", 18))
    return s + TAIL


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: GPL-3.0-only -->
<!-- Generated by scripts/make_icon.py: the adaptive icon (RemoteFM1IOS's icon-light), themed icons from icon-tinted. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def write(rel, text):
    p = os.path.join(RES, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text)
    print(rel)


def legacy(png):
    src = Image.open(io.BytesIO(png)).convert("RGBA")
    for name, px in DENSITIES.items():
        big = px * 4
        img = src.resize((big, big), Image.LANCZOS)
        for kind in ("ic_launcher", "ic_launcher_round"):
            mask = Image.new("L", (big, big), 0)
            d = ImageDraw.Draw(mask)
            m = big * 2 // 48                         # the legacy 48 dp icon's 2 dp margin
            if kind == "ic_launcher":
                d.rounded_rectangle((m, m, big - m, big - m), radius=big * 8 // 48, fill=255)
            else:
                d.ellipse((m, m, big - m, big - m), fill=255)
            out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
            out.paste(img, (0, 0), mask)
            out = out.resize((px, px), Image.LANCZOS)
            rel = "mipmap-%s/%s.png" % (name, kind)
            os.makedirs(os.path.join(RES, os.path.dirname(rel)), exist_ok=True)
            out.save(os.path.join(RES, rel), optimize=True)
            print(rel)


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], "rb") as f:
            png = f.read()
    else:
        png = subprocess.run(["git", "-C", IOS, "show", IOS_COMMIT + ":design/icon/AppIcon.appiconset/AppIcon-light-1024.png"],
                             check=True, capture_output=True).stdout
    write("drawable/ic_launcher_background.xml", background())
    write("drawable/ic_launcher_foreground.xml", foreground())
    write("drawable/ic_launcher_monochrome.xml", monochrome())
    write("mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE)
    write("mipmap-anydpi-v26/ic_launcher_round.xml", ADAPTIVE)
    legacy(png)


if __name__ == "__main__":
    main()
